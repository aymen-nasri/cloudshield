"""Offline baseline model: deterministic, no language model.

It restates the evidence as cited facts and proposes containment only when the evidence is
corroborated (two independent sources, or a high-severity finding). It lets the whole investigation
path (retrieval, rendering, validation, storage, audit) run without AWS, in tests, in the demo and
in the lab. It does not infer intent; Bedrock does that when configured. Its answers pass the same
validation as a real model's.
"""

import json
import re
from typing import Any

_EVIDENCE = re.compile(r'<untrusted_evidence nonce="(\w+)">\n(.*?)\n</untrusted_evidence nonce="\1">', re.S)
_SEVERITY_ORDER = ["informational", "low", "medium", "high", "critical"]
_DETAILS = [
    ("proc.cmdline", "command line"),
    ("api", "API call"),
    ("remote_ip", "from IP"),
    ("srcip", "source IP"),
    ("syscheck.path", "file"),
]
_MISSING = [
    ("pod", [
        "Kubernetes audit log for pods/exec on the affected pod",
        "VPC Flow Logs for the workload since the first event",
        "CloudTrail activity for the workload's IAM role",
    ]),
    ("iam-role", [
        "CloudTrail activity for this role since the first finding",
        "Which workloads hold this role (EKS Pod Identity associations)",
    ]),
    ("host", [
        "Authentication log on the host around the first alert",
        "Running processes and scheduled jobs on the host",
        "VPC Flow Logs for the instance since the first alert",
    ]),
]  # fmt: skip


class OfflineBaselineModel:
    model_id = "cloudshield-offline-baseline-v1"

    def complete(self, system: str, user: str, *, max_tokens: int = 2000) -> str:
        match = _EVIDENCE.search(user)
        if match is None:
            raise ValueError("no evidence block in the prompt")
        evidence: dict[str, Any] = json.loads(match.group(2))
        events: list[dict[str, Any]] = evidence["events"]
        entities: list[dict[str, Any]] = evidence["entities"]

        facts = []
        for e in events:
            where = e.get("resource_id") or "an unresolved resource"
            what = f'"{e["title"]}" ({e.get("event_type")})'
            statement = f"{e['source']} reported {what} on {where} at {e['event_time']}"
            details = e.get("details") or {}
            for key, label in _DETAILS:
                if details.get(key):
                    statement += f"; {label}: {str(details[key])[:160]}"
            facts.append({"statement": statement, "evidence_ids": [e["event_id"]]})

        sources = sorted({e["source"] for e in events})
        ids = [e["event_id"] for e in events]
        hypotheses = [
            {
                "statement": "Independent detectors flagged the same workload; one false positive is unlikely"
                if len(sources) > 1
                # Never "benign": that is the conclusion planted text tries to obtain (eval case s8).
                else "A single detector flagged this; it may be a false positive and needs corroboration",
                "confidence": "medium" if len(sources) > 1 else "low",
                "supporting_evidence": ids,
                "contradicting_evidence": [],
            }
        ]

        worst = max((e["severity"] for e in events), key=_SEVERITY_ORDER.index)
        # One uncorroborated low or medium alert is not enough to disrupt a workload (scenario S6).
        corroborated = len(sources) > 1 or worst in ("high", "critical")
        pods = [x["entity_id"] for x in entities if x["entity_id"].startswith("k8s:pod/")]
        containment = [
            {
                "action_type": "k8s.pod.quarantine_label",
                "target_entity_id": pods[0],
                "rationale": "Cuts the pod's network access while keeping it running for forensics",
                "expected_blast_radius": "This replica stops serving; the workload's other replicas continue",
                "prerequisites": ["Confirm the workload has other healthy replicas"],
            }
        ] if pods and corroborated else []  # fmt: skip

        kinds = {x.get("kind") for x in entities}
        missing = [item for kind, items in _MISSING if kind in kinds for item in items]
        synopsis = (
            f"{len(events)} event(s) from {', '.join(sources)} on "
            f"{events[0].get('resource_id') or 'an unresolved resource'}; highest severity {worst}."
        )
        return json.dumps(
            {
                "synopsis": synopsis[:600],
                "observed_facts": facts,
                "hypotheses": hypotheses,
                "missing_evidence": missing or ["Context for the affected resource could not be resolved"],
                "containment_options": containment,
                "confidence_limits": (
                    "Generated by the offline baseline (no language model): it restates the evidence and "
                    "does not judge intent."
                ),
            }
        )
